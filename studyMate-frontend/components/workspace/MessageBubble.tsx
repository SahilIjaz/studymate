"use client";

import { AlertCircle, Check, Copy } from "lucide-react";
import { motion } from "motion/react";
import { useState } from "react";
import type { Message } from "@/lib/api";
import { type Stage, useStore } from "@/lib/store";
import { cn, pageLabel } from "@/lib/utils";
import { LogoMark } from "../ui/Logo";
import { AnswerMarkdown } from "./AnswerMarkdown";
import { StatusLine } from "./StatusLine";

export function MessageBubble({ message, isLast, stage }: { message: Message; isLast: boolean; stage: Stage }) {
  const selected = useStore((s) => s.selectedCitation);
  const select = useStore((s) => s.selectCitation);
  const [copied, setCopied] = useState(false);

  if (message.role === "user") {
    return (
      <motion.div
        initial={{ opacity: 0, y: 10, scale: 0.98 }}
        animate={{ opacity: 1, y: 0, scale: 1 }}
        transition={{ type: "spring", stiffness: 380, damping: 30 }}
        className="flex justify-end"
      >
        <div className="max-w-[85%] rounded-[20px] rounded-br-md bg-user px-4 py-2.5 text-[15px] leading-relaxed text-user-fg whitespace-pre-wrap sm:max-w-[70%]">
          {message.content}
        </div>
      </motion.div>
    );
  }

  const streaming = message.status === "streaming";
  const failed = message.status === "failed";
  const showStatus = streaming && isLast && stage && stage !== "answering" && !message.content;
  const activeN = selected?.messageId === message.id ? selected.n : null;
  const documents = [...new Set(message.citations.map((c) => c.filename))];

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(message.content);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      /* clipboard blocked */
    }
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ type: "spring", stiffness: 380, damping: 30 }}
      className="flex gap-3"
    >
      <div className="mt-1 hidden h-7 w-7 shrink-0 items-center justify-center rounded-lg bg-surface-2 ring-1 ring-border sm:flex">
        <LogoMark size={18} />
      </div>
      <div className="min-w-0 flex-1">
        {showStatus ? (
          <StatusLine stage={stage} sourceCount={message.citations.length} />
        ) : (
          <AnswerMarkdown
            content={message.content}
            citations={message.citations}
            activeCitation={activeN}
            streaming={streaming}
            onSelectCitation={(n) => select(activeN === n ? null : { messageId: message.id, n })}
          />
        )}

        {failed && (
          <p className="mt-2 flex items-center gap-1.5 text-[13px] text-danger">
            <AlertCircle size={14} /> This answer didn&apos;t complete.
          </p>
        )}
        {message.status === "interrupted" && <p className="mt-2 text-[13px] text-ink-3">Stopped.</p>}

        {!streaming && message.content && (
          <div className="mt-2.5 flex flex-wrap items-center gap-x-3 gap-y-1.5 text-[12.5px] text-ink-3">
            {message.citations.length > 0 && (
              <button
                type="button"
                onClick={() => select({ messageId: message.id, n: message.citations[0].n })}
                className="inline-flex items-center gap-1.5 rounded-md py-0.5 hover:text-ink"
              >
                <span className="inline-flex -space-x-1">
                  {message.citations.slice(0, 4).map((c) => (
                    <span
                      key={c.n}
                      className="inline-flex h-4 min-w-4 items-center justify-center rounded-[4px] bg-mark px-1 font-mono text-[10px] text-mark-ink ring-1 ring-surface"
                    >
                      {c.n}
                    </span>
                  ))}
                </span>
                <span>
                  {message.citations.length} source{message.citations.length === 1 ? "" : "s"}
                  <span className="hidden sm:inline">
                    {" "}
                    · {documents.length === 1 ? `${documents[0]}, ` : ""}
                    {message.citations
                      .slice(0, 3)
                      .map((c) => pageLabel(c.page_start, c.page_end))
                      .join(", ")}
                  </span>
                </span>
              </button>
            )}
            {message.usage?.output_tokens != null && (
              <span className="tabular hidden sm:inline" title="Tokens generated by Claude">
                {message.usage.output_tokens} tokens
                {message.usage.cache_read_input_tokens ? " · cached prompt" : ""}
              </span>
            )}
            <button
              type="button"
              onClick={copy}
              className={cn("inline-flex items-center gap-1 rounded-md py-0.5 hover:text-ink", copied && "text-ok")}
            >
              {copied ? <Check size={13} /> : <Copy size={13} />}
              {copied ? "Copied" : "Copy"}
            </button>
          </div>
        )}
      </div>
    </motion.div>
  );
}
